const r2 = await a("POST", `/purchases/suppliers/${sups[1].id}/pay`, { amount: 1000000, currency: "SYP", boxId: box.id });
console.log("supplier pay exact SYP after rate fell:", r2.status, JSON.stringify(r2.json).slice(0, 200));
