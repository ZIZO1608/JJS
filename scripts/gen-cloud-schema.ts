/**
 * Writes cloud/schema.sql: the Supabase (Postgres) tables that receive the laptop's data.
 * Run after any change to server/db/schema.ts:  npx tsx scripts/gen-cloud-schema.ts
 * The cloud copy is one-way and read-only for people: only the laptop (service key) writes.
 */
import fs from "node:fs";
import path from "node:path";
import { getTableConfig, type SQLiteTable } from "drizzle-orm/sqlite-core";
import * as schema from "../server/db/schema.js";
import { SYNC_TABLES } from "../server/services/sync.js";

const pgType = (columnType: string, mode?: string) => {
  if (columnType === "SQLiteBoolean" || mode === "boolean") return "boolean";
  if (columnType.includes("Integer") || columnType === "SQLiteTimestamp") return "bigint";
  if (columnType === "SQLiteReal" || columnType.includes("Numeric")) return "double precision";
  return "text";
};

const tables = Object.values(schema).filter((v): v is SQLiteTable => {
  try {
    return !!getTableConfig(v as SQLiteTable).name;
  } catch {
    return false;
  }
});

let out = `-- JJ's ERP — cloud copy for Supabase. Generated by scripts/gen-cloud-schema.ts. Do not edit by hand.
-- Paste into Supabase → SQL editor → Run. Then put the project URL and the service_role key
-- in the app: Settings → Network & cloud.
-- Row level security is ON for every table and there are no policies, so nobody can read or
-- write with the public (anon) key. The laptop uses the service_role key, which bypasses RLS.
-- The phone dashboard reads only "daily_snapshots", and only for signed-in users you invite.

`;
for (const t of tables) {
  const cfg = getTableConfig(t);
  if (!(SYNC_TABLES as readonly string[]).includes(cfg.name)) continue;
  const cols = cfg.columns.filter((c) => !(cfg.name === "users" && c.name === "password_hash")).map((c) => {
    const type = pgType(c.columnType, (c as unknown as { config?: { mode?: string } }).config?.mode);
    const pk = c.primary ? " primary key" : "";
    return `  "${c.name}" ${type}${pk}`;
  });
  out += `create table if not exists public."${cfg.name}" (\n${cols.join(",\n")}\n);\nalter table public."${cfg.name}" enable row level security;\n\n`;
}
out += `-- one small JSON summary per day for the owner's phone
create table if not exists public.daily_snapshots (
  "date" text primary key,
  "data" jsonb not null,
  "updated_at" text not null
);
alter table public.daily_snapshots enable row level security;
drop policy if exists "signed-in users read snapshots" on public.daily_snapshots;
create policy "signed-in users read snapshots" on public.daily_snapshots for select to authenticated using (true);
`;
const file = path.join(process.cwd(), "cloud", "schema.sql");
fs.writeFileSync(file, out);
console.log(`wrote ${file} (${tables.length} tables scanned)`);
